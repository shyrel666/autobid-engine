import { chromium, api, BASE, assert, recorder, shot, newPage } from './lib.mjs'
const suite = recorder('file-processing')
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE })
const { context, page, errors } = await newPage(browser)
page.setDefaultTimeout(10000)
let zipTask, candidate
const poll = async (what, fn) => {
  for (let i = 0; i < 200; i++) {
    const v = await fn()
    if (v) return v
    await new Promise((r) => setTimeout(r, 100))
  }
  throw new Error(`等待超时：${what}`)
}
const waitDocs = (task) => poll('文档入库', async () => (await api('GET', `/api/tasks/${task}/documents`)).length > 0)
const waitRecord = (task) => poll('候选就绪', async () => (await api('GET', `/api/tasks/${task}/file-processing-records`)).find((r) => r.status === 'ready'))
const revTask = Number(process.env.E2E_REV_TASK), revDoc = Number(process.env.E2E_REV_DOC)
try {
  await suite.check('ZIP 页面上传、子文件导入、刷新后状态保留', async () => {
    zipTask = (await api('POST', '/api/tasks', { name: 'ZIP 浏览器验收', goal: '核对附件', start: false })).id
    await page.goto(`${BASE}/tasks/${zipTask}/documents`)
    await page.getByLabel('招标编号 *', { exact: false }).fill('BROWSER-ZIP')
    await page.locator('input[type=file]').first().setInputFiles(process.env.E2E_ZIP)
    await page.getByRole('button', { name: '导入并解析', exact: true }).click()
    await page.getByText('原件与 ZIP 子文件', { exact: false }).waitFor()
    await page.reload()
    const files = (await api('GET', `/api/tasks/${zipTask}/files`)).files
    const child = files.find((f) => f.format === 'csv' && f.parent_file_id)
    assert(child, 'ZIP CSV child missing')
    await page.getByLabel('附件招标编号', { exact: true }).fill('BROWSER-ZIP')
    await page.getByLabel(`选择 ${child.archive_path}`, { exact: true }).check()
    // 候选模式是默认值（S5a）；这里验证直接导入，所以取消勾选。
    await page.getByLabel(/先生成候选/).uncheck()
    await page.getByRole('button', { name: '导入所选文件（1）', exact: true }).click()
    await waitDocs(zipTask)
    await page.reload()
    const docs = await api('GET', `/api/tasks/${zipTask}/documents`)
    assert(docs.length === 1 && docs[0].original_file_id === child.id, 'child import/provenance failed')
    await page.getByText('已采用', { exact: true }).first().waitFor()
    await shot(page, 'file-processing-zip-import')
  })
  await suite.check('重新解析只生成候选、差异预览、刷新后采用、要求门禁', async () => {
    await page.goto(`${BASE}/tasks/${revTask}/documents?doc=${revDoc}`)
    await page.getByRole('button', { name: '重新解析并预览', exact: true }).click()
    const ready = await waitRecord(revTask)
    await page.reload()
    await page.getByRole('button', { name: `核对候选 #${ready.id}`, exact: true }).click()
    const modal = page.getByRole('dialog')
    await modal.getByText('旧解析：遗漏设备数量', { exact: true }).waitFor()
    await modal.getByText('服务器', { exact: false }).waitFor()
    candidate = (await api('GET', `/api/tasks/${revTask}/file-processing-records`))[0]
    assert((await api('GET', `/api/tasks/${revTask}/documents`))[0].parse_revision === 0, 'preview mutated document')
    await shot(page, 'file-processing-revision-preview')
    await page.reload()
    await page.getByRole('button', { name: `核对候选 #${candidate.id}`, exact: true }).click()
    await modal.getByLabel('复核说明', { exact: false }).fill('已核对原件数量')
    await modal.getByRole('button', { name: '确认采用此修订', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    await page.getByText('修订已采用，请重新提取并复核要求后再确认、导出。', { exact: false }).waitFor()
    const doc = (await api('GET', `/api/tasks/${revTask}/documents`))[0]
    assert(doc.id === revDoc && doc.parse_revision === 1, 'revision adoption failed')
    const readiness = await api('GET', `/api/tasks/${revTask}/export-readiness`)
    assert(readiness.counts.requirements_source_changed > 0, 'source gate missing')
    await page.reload()
    await page.getByRole('button', { name: `查看 #${candidate.id}`, exact: true }).click()
    await page.getByText('此候选已采用', { exact: false }).waitFor()
    await modal.getByRole('button', { name: '关闭', exact: true }).click()
  })
  await suite.check('过期候选禁止采用、移动端无横向溢出', async () => {
    const a = await api('POST', `/api/tasks/${revTask}/documents/${revDoc}/reparse`, { request_key: 'browser-stale-a', expected_revision: 1 })
    const b = await api('POST', `/api/tasks/${revTask}/documents/${revDoc}/reparse`, { request_key: 'browser-stale-b', expected_revision: 1 })
    await api('POST', `/api/tasks/${revTask}/file-processing-records/${a.id}/adopt`, { expected_revision: 1 })
    await page.goto(`${BASE}/tasks/${revTask}/documents`)
    await page.getByRole('button', { name: `核对候选 #${b.id}`, exact: true }).click()
    await page.getByText('文档版本已变化，此候选已失效，请关闭后重新解析。', { exact: true }).waitFor()
    assert(await page.getByRole('button', { name: '确认采用此修订', exact: true }).isDisabled(), 'stale candidate adopt enabled')
    await page.setViewportSize({ width: 390, height: 844 })
    await shot(page, 'file-processing-mobile')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'horizontal overflow')
  })
  await suite.check('必需材料缺失门禁、流式上传、后台展开与清单绑定', async () => {
    await page.setViewportSize({ width: 1280, height: 900 })
    const task = (await api('POST', '/api/tasks', { name: '固定处理增强验收', goal: '收齐附件', start: false })).id
    await page.goto(`${BASE}/tasks/${task}/documents`)
    await page.getByLabel('新增必需材料名称').fill('设备清单附件')
    await page.getByRole('button', { name: '登记必需材料', exact: true }).click()
    await page.getByText('设备清单附件', { exact: true }).waitFor()
    assert((await api('GET', `/api/tasks/${task}/export-readiness`)).counts.required_material_incomplete === 1, 'missing-material gate absent')
    await page.getByLabel('选择后台处理原件', { exact: true }).setInputFiles(process.env.E2E_ZIP)
    await page.getByRole('button', { name: '上传原件', exact: true }).click()
    await page.getByText('已展开', { exact: true }).waitFor()
    await page.reload()
    const child = (await api('GET', `/api/tasks/${task}/files`)).files.find((f) => f.format === 'csv' && f.parent_file_id)
    assert(child, 'streamed ZIP not expanded')
    await page.getByLabel('绑定原件', { exact: true }).selectOption(String(child.id))
    await page.getByRole('button', { name: '保存材料', exact: true }).click()
    await page.getByText('必需 · 尚未正式导入', { exact: true }).waitFor()
    await page.getByLabel('附件招标编号', { exact: true }).fill('BROWSER-ASYNC')
    await page.getByLabel(`选择 ${child.archive_path}`, { exact: true }).check()
    await page.getByLabel(/先生成候选/).uncheck()
    await page.getByRole('button', { name: '导入所选文件（1）', exact: true }).click()
    await page.getByText('必需 · 已完成', { exact: true }).waitFor()
    assert(!(await api('GET', `/api/tasks/${task}/export-readiness`)).counts.required_material_incomplete, 'completed material still blocked')
    await page.reload()
    await page.getByText('必需 · 已完成', { exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await shot(page, 'fixed-workflow-mobile')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'workflow horizontal overflow')
  })
  assert(errors.length === 0, errors.join('\n'))
} finally {
  await context.close(); await browser.close()
  if (await suite.save()) process.exitCode = 1
}
