// Run via TestModelSettingsBrowser; the Go harness owns an isolated DB schema.
import { chromium, api, BASE, OUT, assert, recorder, shot, newPage } from './lib.mjs'
const suite = recorder('model-settings')
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE })
const { context, page, errors } = await newPage(browser)
page.setDefaultTimeout(8000)
const modelBase = process.env.E2E_MODEL_BASE
if (!modelBase) throw new Error('E2E_MODEL_BASE must come from the isolated Go harness')
const card = (name) => page.locator('article').filter({ has: page.getByRole('button', { name: `编辑 ${name}`, exact: true }) })
const drawer = () => page.getByRole('dialog').first()
const close = () => drawer().getByRole('button', { name: '关闭', exact: true }).click()
let first
try {
  await suite.check('空库、创建抽屉、模型发现及当前参数连接测试', async () => {
    await page.goto(BASE + '/llm')
    await page.getByText('还没有模型配置', { exact: false }).waitFor()
    await page.getByRole('button', { name: '新建', exact: true }).click()
    await page.getByRole('textbox', { name: '名称', exact: true }).fill('写作主模型')
    await page.getByLabel('协议格式', { exact: true }).selectOption('openai')
    await page.getByLabel('Base URL', { exact: true }).fill(modelBase + '/chat/completions')
    await page.getByLabel('API Key', { exact: true }).fill('browser-fixture-key')
    await page.getByRole('button', { name: '加载可用模型' }).click()
    await page.getByLabel('可用模型', { exact: true }).selectOption('fixture-chat')
    await page.getByLabel('最大输出 tokens', { exact: true }).fill('2048')
    await page.getByLabel('输出上限字段', { exact: true }).selectOption('max_completion_tokens')
    await page.getByLabel('思考开关', { exact: true }).selectOption('enabled')
    await page.getByLabel('思考强度', { exact: true }).selectOption('high')
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByText('回复：fixture OK').waitFor()
    await page.getByRole('switch', { name: '流式输出', exact: true }).uncheck()
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByText('回复：fixture OK').waitFor()
    await shot(page, 'model-editor-desktop')
    await page.getByRole('button', { name: '新建配置', exact: true }).click()
    await card('写作主模型').waitFor()
    const profiles = await api('GET', '/api/llm/profiles')
    first = profiles[0]
    assert(first.base_url === modelBase && !first.is_default, 'URL normalization or activation state incorrect')
    assert(!JSON.stringify(profiles).includes('browser-fixture-key'), 'credential exposed')
  })
  await suite.check('激活、Key 留空保留、绑定刷新回显', async () => {
    await card('写作主模型').getByRole('button', { name: '设为激活' }).click()
    await card('写作主模型').getByRole('button', { name: '已激活' }).waitFor()
    assert(await card('写作主模型').getByRole('button', { name: '删除 写作主模型' }).isDisabled(), 'active can be deleted')
    await page.getByRole('button', { name: '编辑 写作主模型', exact: true }).click()
    assert(await page.getByLabel('API Key', { exact: true }).inputValue() === '', 'secret shown in editor')
    await page.getByLabel('每秒限速', { exact: true }).fill('2')
    await page.getByRole('button', { name: '保存配置', exact: true }).click()
    await drawer().waitFor({ state: 'hidden' })
    await page.getByLabel('Worker（执行单元）', { exact: true }).selectOption(String(first.id))
    await page.getByRole('button', { name: '应用', exact: true }).nth(1).click()
    await page.getByText('模型绑定已保存', { exact: true }).waitFor()
    await page.reload()
    await page.waitForFunction((id) => document.querySelector('select[aria-label="Worker（执行单元）"]')?.value === String(id), first.id)
    assert((await api('GET', `/api/llm/profiles/${first.id}`)).key_configured, 'blank key erased credential')
  })
  await suite.check('未保存保护、失败反馈、Responses 协议', async () => {
    await page.getByRole('button', { name: '编辑 写作主模型', exact: true }).click()
    await page.getByLabel('模型', { exact: true }).fill('fixture-reject')
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByText('连接失败：', { exact: false }).waitFor()
    await close()
    await page.getByRole('button', { name: '放弃修改', exact: true }).click()
    await drawer().waitFor({ state: 'hidden' })
    const second = await api('POST', '/api/llm/profiles', { name: '备用 Responses', model: 'fixture-responses', format: 'openai-responses', base_url: modelBase, api_key: 'browser-fixture-key', enabled: true, in_global_pool: true, streaming: false, priority: 8 })
    await page.getByRole('button', { name: '刷新模型配置' }).click()
    await page.getByRole('button', { name: '编辑 备用 Responses', exact: true }).click()
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByText('回复：responses OK').waitFor()
    await close()
    assert(second.id > first.id, 'backup not saved')
  })
  await suite.check('轮询与重试保存、恢复和排序', async () => {
    await page.getByRole('button', { name: '轮询配置', exact: true }).click()
    await page.getByRole('switch', { name: '启用轮询', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('input[aria-label="启用轮询"]')?.checked === true)
    await page.getByRole('switch', { name: 'Agent 绑定失败时兜底', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('input[aria-label="Agent 绑定失败时兜底"]')?.checked === true)
    await page.getByRole('button', { name: '全部恢复', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('input[aria-label="启用轮询"]')?.disabled)
    await shot(page, 'model-pool-desktop')
    await close()
    await page.getByRole('tab', { name: '重试与退避', exact: true }).click()
    await page.getByLabel('建连重试次数', { exact: true }).fill('4')
    await page.getByLabel('空响应重试次数', { exact: true }).fill('-1')
    await page.getByRole('button', { name: '保存策略', exact: true }).click()
    await page.getByText('重试策略已保存', { exact: true }).waitFor()
    const s = await api('GET', '/api/llm/settings')
    assert(s.pool_enabled && s.bind_fallback && s.retry.connect.attempts === 4 && s.retry.empty.attempts === -1, 'policy not persisted')
    const pool = await api('GET', '/api/llm/pool')
    assert(pool.chain[0].profile_id === first.id && pool.chain[0].order === 1, 'active model not first')
    await page.getByRole('tab', { name: '模型配置', exact: true }).click()
    await page.getByText('重试策略已保存', { exact: true }).waitFor({ state: 'hidden' })
    await shot(page, 'model-cards-desktop')
  })
  await suite.check('390px 小屏卡片与编辑抽屉无横向溢出', async () => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '编辑 写作主模型', exact: true }).click()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'page overflows viewport')
    const box = await drawer().boundingBox()
    assert(box.x >= 0 && box.x + box.width <= 391, 'drawer outside viewport')
    await shot(page, 'model-editor-mobile')
    await close()
    assert(errors.length === 0, `browser errors: ${errors.join('; ')}`)
  })
} finally {
  const failed = await suite.save()
  await context.close()
  await browser.close()
  if (failed) process.exitCode = 1
  console.log(`Artifacts: ${OUT}`)
}
